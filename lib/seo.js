function safeLocale(locale) {
  return SEO_LOCALES.includes(locale)
    ? locale
    : 'en';
}

export function normalisePath(path) {
  if (!path || path === '/') {
    return '/';
  }

  const clean =
    `/${String(path)}`
      .replace(/\/+/g, '/')
      .replace(/\/$/, '');

  return clean || '/';
}

export function localisedPath(
  locale,
  path
) {
  const safe =
    safeLocale(locale);

  const clean =
    normalisePath(path);

  if (safe === 'en') {
    return clean;
  }

  return (
    `/${safe}` +
    (clean === '/' ? '' : clean)
  );
}

export function absoluteUrl(path) {
  const clean =
    normalisePath(path);

  return (
    SITE_URL +
    (clean === '/' ? '/' : clean)
  );
}

export function languageAlternates(
  path
) {
  const clean =
    normalisePath(path);

  return {
    en:
      absoluteUrl(
        localisedPath('en', clean)
      ),
    tr:
      absoluteUrl(
        localisedPath('tr', clean)
      ),
    ar:
      absoluteUrl(
        localisedPath('ar', clean)
      ),
    'x-default':
      absoluteUrl(
        localisedPath('en', clean)
      )
  };
}

function humanisePath(path) {
  const last =
    normalisePath(path)
      .split('/')
      .filter(Boolean)
      .pop();

  if (!last) {
    return 'Restaurant Management Platform';
  }

  return last
    .split('-')
    .map(
      (part) =>
        part.charAt(0).toUpperCase() +
        part.slice(1)
    )
    .join(' ');
}

export function getSeoCopy(
  locale,
  path
) {
  const safe =
    safeLocale(locale);

  const clean =
    normalisePath(path);

  const exact =
    COPY[safe][clean];

  if (exact) {
    return exact;
  }

  if (
    clean.startsWith('/solutions/')
  ) {
    return COPY[safe]['/solutions'];
  }

  if (
    clean.startsWith('/resources/')
  ) {
    return COPY[safe]['/resources'];
  }

  return {
    title:
      humanisePath(clean),
    description:
      COPY[safe]['/'].description
  };
}

function titleText(value) {
  if (
    typeof value === 'string'
  ) {
    return value;
  }

  return '';
}

function brandedTitle(value) {
  const title =
    titleText(value).trim() ||
    'Restaurant Management Platform';

  return /paymydine/i.test(title)
    ? title
    : `${title} | PayMyDine`;
}

function commonMetadata(
  locale,
  path,
  title,
  description
) {
  const safe =
    safeLocale(locale);

  const clean =
    normalisePath(path);

  const canonical =
    absoluteUrl(
      localisedPath(
        safe,
        clean
      )
    );

  const alternates =
    languageAlternates(clean);

  const branded =
    brandedTitle(title);

  const socialImage =
    absoluteUrl(
      '/site-assets/custom/seo/paymydine-social-share.png'
    );

  const otherLocales =
    SEO_LOCALES
      .filter(
        (item) =>
          item !== safe
      )
      .map(
        (item) =>
          OPEN_GRAPH_LOCALES[item]
      );

  return {
    metadataBase:
      new URL(SITE_URL),

    applicationName:
      'PayMyDine',

    description,

    authors: [
      {
        name: 'PayMyDine',
        url: SITE_URL
      }
    ],

    creator:
      'PayMyDine',

    publisher:
      'PayMyDine',

    category:
      'Restaurant technology',

    referrer:
      'origin-when-cross-origin',

    formatDetection: {
      email: false,
      address: false,
      telephone: false
    },

    alternates: {
      canonical,
      languages: alternates
    },

    openGraph: {
      title: branded,
      description,
      url: canonical,
      siteName: 'PayMyDine',
      locale:
        OPEN_GRAPH_LOCALES[safe],
      alternateLocale:
        otherLocales,
      type: 'website',
      images: [
        {
          url: socialImage,
          width: 1200,
          height: 630,
          alt: 'PayMyDine — AI-Powered Restaurant Management'
        }
      ]
    },

    twitter: {
      card: 'summary_large_image',
      title: branded,
      description,
      images: [
        socialImage
      ]
    },

    robots: {
      index: true,
      follow: true,
      googleBot: {
        index: true,
        follow: true,
        'max-video-preview': -1,
        'max-image-preview': 'large',
        'max-snippet': -1
      }
    },

    icons: {
      icon: '/icon.svg'
    },

    manifest:
      '/manifest.webmanifest',

    other: {
      'content-language':
        HTML_LANGUAGES[safe]
    }
  };
}

export function siteRootMetadata(
  locale,
  overrides = {}
) {
  const safe =
    safeLocale(locale);

  const fallback =
    getSeoCopy(safe, '/');

  const title =
    overrides.title ||
    fallback.title;

  const description =
    overrides.description ||
    fallback.description;

  const metadata =
    commonMetadata(
      safe,
      '/',
      title,
      description
    );

  return {
    ...metadata,

    title: {
      default:
        brandedTitle(title),
      template:
        '%s | PayMyDine'
    }
  };
}

export function metadataForRoute(
  locale,
  path,
  overrides = {}
) {
  const safe =
    safeLocale(locale);

  const clean =
    normalisePath(path);

  const fallback =
    getSeoCopy(
      safe,
      clean
    );

  const title =
    overrides.title ||
    fallback.title;

  const description =
    overrides.description ||
    fallback.description;

  const metadata =
    commonMetadata(
      safe,
      clean,
      title,
      description
    );

  return {
    ...metadata,

    title: {
      absolute:
        brandedTitle(title)
    }
  };
}
